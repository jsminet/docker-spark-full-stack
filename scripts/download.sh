#!/bin/bash

MAVEN_MIRROR=https://repo1.maven.org/maven2
KYUUBI_VERSION=1.10.0
SPARK_VERSION=3.5.1
HADOOP_MAJOR_VERSION=3
AWS_JAVA_SDK_VERSION=1.12.757
SPARK_HADOOP_VERSION=3.3.4
KYUUBI_HADOOP_VERSION=3.3.6
HIVE_VERSION=3.1.3
ICEBERG_VERSION=1.5.2
POSTGRES_VERSION=12
POSTGRES_JDBC_VERSION=42.7.3
SCALA_BINARY_VERSION=2.12
SPARK_BINARY_VERSION=3.5

ICEBERG_SPARK_JAR_NAME=iceberg-spark-runtime-${SPARK_BINARY_VERSION}_$SCALA_BINARY_VERSION
SPARK_HADOOP_CLOUD_JAR_NAME=spark-hadoop-cloud_$SCALA_BINARY_VERSION
HADOOP_CLOUD_STORAGE_JAR_NAME=hadoop-cloud-storage
HADOOP_AWS_JAR_NAME=hadoop-aws
AWS_JAVA_SDK_BUNDLE_JAR_NAME=aws-java-sdk-bundle
POSTGRES_JDBC_JAR_NAME=postgresql
TPCDS_CONNECTOR_JAR_NAME=kyuubi-spark-connector-tpcds_$SCALA_BINARY_VERSION
TPCH_CONNECTOR_JAR_NAME=kyuubi-spark-connector-tpch_$SCALA_BINARY_VERSION
KYUUBI_HOME=/opt/apache-kyuubi-$KYUUBI_VERSION-bin

curl $MAVEN_MIRROR/org/apache/iceberg/$ICEBERG_SPARK_JAR_NAME/$ICEBERG_VERSION/$ICEBERG_SPARK_JAR_NAME-$ICEBERG_VERSION.jar \
-o ../app/spark/jars/$ICEBERG_SPARK_JAR_NAME-$ICEBERG_VERSION.jar

curl $MAVEN_MIRROR/org/apache/spark/$SPARK_HADOOP_CLOUD_JAR_NAME/$SPARK_VERSION/$SPARK_HADOOP_CLOUD_JAR_NAME-$SPARK_VERSION.jar \
-o ../app/spark/jars/$SPARK_HADOOP_CLOUD_JAR_NAME-$SPARK_VERSION.jar

curl $MAVEN_MIRROR/org/apache/hadoop/$HADOOP_CLOUD_STORAGE_JAR_NAME/$SPARK_HADOOP_VERSION/$HADOOP_CLOUD_STORAGE_JAR_NAME-$SPARK_HADOOP_VERSION.jar \
-o ../app/spark/jars/$HADOOP_CLOUD_STORAGE_JAR_NAME-$SPARK_HADOOP_VERSION.jar

curl $MAVEN_MIRROR/org/apache/hadoop/$HADOOP_CLOUD_STORAGE_JAR_NAME/$KYUUBI_HADOOP_VERSION/$HADOOP_CLOUD_STORAGE_JAR_NAME-$KYUUBI_HADOOP_VERSION.jar \
-o ../app/kyuubi/jars/$HADOOP_CLOUD_STORAGE_JAR_NAME-$KYUUBI_HADOOP_VERSION.jar

curl $MAVEN_MIRROR/org/apache/hadoop/$HADOOP_AWS_JAR_NAME/$SPARK_HADOOP_VERSION/$HADOOP_AWS_JAR_NAME-$SPARK_HADOOP_VERSION.jar \
-o ../app/spark/jars/$HADOOP_AWS_JAR_NAME-$SPARK_HADOOP_VERSION.jar

curl $MAVEN_MIRROR/org/apache/hadoop/$HADOOP_AWS_JAR_NAME/$KYUUBI_HADOOP_VERSION/$HADOOP_AWS_JAR_NAME-$KYUUBI_HADOOP_VERSION.jar \
-o ../app/kyuubi/jars/$HADOOP_AWS_JAR_NAME-$KYUUBI_HADOOP_VERSION.jar

curl $MAVEN_MIRROR/com/amazonaws/$AWS_JAVA_SDK_BUNDLE_JAR_NAME/$AWS_JAVA_SDK_VERSION/$AWS_JAVA_SDK_BUNDLE_JAR_NAME-$AWS_JAVA_SDK_VERSION.jar \
-o ../app/spark/jars/$AWS_JAVA_SDK_BUNDLE_JAR_NAME-$AWS_JAVA_SDK_VERSION.jar

curl $MAVEN_MIRROR/com/amazonaws/$AWS_JAVA_SDK_BUNDLE_JAR_NAME/$AWS_JAVA_SDK_VERSION/$AWS_JAVA_SDK_BUNDLE_JAR_NAME-$AWS_JAVA_SDK_VERSION.jar \
-o ../app/kyuubi/jars/$AWS_JAVA_SDK_BUNDLE_JAR_NAME-$AWS_JAVA_SDK_VERSION.jar

curl $MAVEN_MIRROR/org/postgresql/$POSTGRES_JDBC_JAR_NAME/$POSTGRES_JDBC_VERSION/$POSTGRES_JDBC_JAR_NAME-$POSTGRES_JDBC_VERSION.jar \
-o ../app/spark/jars/$POSTGRES_JDBC_JAR_NAME-$POSTGRES_JDBC_VERSION.jar

curl $MAVEN_MIRROR/org/apache/kyuubi/$TPCDS_CONNECTOR_JAR_NAME/$KYUUBI_VERSION/$TPCDS_CONNECTOR_JAR_NAME-$KYUUBI_VERSION.jar \
-o ../app/spark/jars/$TPCDS_CONNECTOR_JAR_NAME-$KYUUBI_VERSION.jar

curl $MAVEN_MIRROR/org/apache/kyuubi/$TPCH_CONNECTOR_JAR_NAME/$KYUUBI_VERSION/$TPCH_CONNECTOR_JAR_NAME-$KYUUBI_VERSION.jar \
-o ../app/spark/jars/$TPCH_CONNECTOR_JAR_NAME-$KYUUBI_VERSION.jar